SELECT
    R.REQUEST_ID,
    R.TITLE,
    C.CATEGORY_NAME,
    U.FULL_NAME AS SUBMITTED_BY,
    R.PRIORITY,
    R.STATUS
FROM REQUESTS R
JOIN CATEGORIES C
    ON R.CATEGORY_ID = C.CATEGORY_ID
JOIN USERS U
    ON R.SUBMITTED_BY = U.USER_ID
ORDER BY R.REQUEST_ID;