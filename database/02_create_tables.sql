CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PHONE VARCHAR2(15),
    USER_ROLE VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL,

    CONSTRAINT CHK_USER_ROLE
    CHECK (USER_ROLE IN ('STUDENT', 'STAFF', 'ADMIN'))
);

CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(200)
);

CREATE TABLE REQUESTS (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    TITLE VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL,
    LOCATION VARCHAR2(150) NOT NULL,

    CATEGORY_ID NUMBER NOT NULL,
    SUBMITTED_BY NUMBER NOT NULL,
    ASSIGNED_TO NUMBER,

    PRIORITY VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    RESOLVED_AT TIMESTAMP,

    CONSTRAINT FK_REQUEST_CATEGORY
    FOREIGN KEY (CATEGORY_ID)
    REFERENCES CATEGORIES(CATEGORY_ID),

    CONSTRAINT FK_REQUEST_STUDENT
    FOREIGN KEY (SUBMITTED_BY)
    REFERENCES USERS(USER_ID),

    CONSTRAINT FK_REQUEST_STAFF
    FOREIGN KEY (ASSIGNED_TO)
    REFERENCES USERS(USER_ID),

    CONSTRAINT CHK_REQUEST_PRIORITY
    CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH')),

    CONSTRAINT CHK_REQUEST_STATUS
    CHECK (STATUS IN ('PENDING', 'IN PROGRESS', 'RESOLVED', 'REJECTED'))
);


SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN ('USERS', 'CATEGORIES', 'REQUESTS')
ORDER BY TABLE_NAME;